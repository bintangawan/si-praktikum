export function localizeServerMessage(locale: Locale, message: string): string {
  if (locale !== 'en') return message;
  const exact = englishServerMessages[message];
  if (exact) return exact;
  const staffMatch = message.match(/^Akun (Dosen|Laboran|Aslab) tidak ditemukan atau belum disetujui\.$/);
  if (staffMatch) return `The ${({ Dosen: 'lecturer', Laboran: 'lab administrator', Aslab: 'lab assistant' })[staffMatch[1] as 'Dosen' | 'Laboran' | 'Aslab']} account could not be found or has not been approved.`;
  const statusMatch = message.match(/^Status (ACC|REVISI|DITOLAK) berhasil disimpan\.$/);
  if (statusMatch) return `The ${({ ACC: 'approval', REVISI: 'revision request', DITOLAK: 'rejection' })[statusMatch[1] as 'ACC' | 'REVISI' | 'DITOLAK']} status was saved.`;
  const importRowMatch = message.match(/^Kolom id, name, email, dan role wajib diisi pada baris (.+)\.$/);
  if (importRowMatch) return `The id, name, email, and role fields are required on row ${importRowMatch[1]}.`;
  if (/\b(?:tidak|belum|sudah|akun|kelas|mahasiswa|dosen|laboran|aslab|pengumpulan|laporan|modul|presensi|semester|perubahan|berhasil|gagal|diisi|diperbarui|diproses|dihapus|ditambahkan|menunggu|silakan|gunakan|wajib|pilih|aktifkan|ditemukan|ditutup)\b/i.test(message)) return localeCopy.en['ui.requestFailed'];
  return message;
}

export function getCookieLocale(cookieName: string, fallback: Locale = 'id'): Locale {
  if (typeof document === 'undefined') return fallback;
  const value = document.cookie.split('; ').find((entry) => entry.startsWith(`${cookieName}=`))?.split('=')[1];
  return value === 'en' ? 'en' : value === 'id' ? 'id' : fallback;
}
